#!/usr/bin/env python3
"""Build the browser (WebAssembly) bundle with pygbag.

Stages ``web/main.py`` plus the ``jenesboat_v2`` package into ``build/web-stage/jenesboat``,
stamps ``_build_info.py`` with the build id, runs pygbag and copies the result to ``--out``.

    uv run python scripts/build_web.py --build-id abc1234 --sha <full sha> --out dist/web
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "jenesboat_v2"
WEB = ROOT / "web"
STAGE = ROOT / "build" / "web-stage" / "jenesboat"  # folder name becomes the .apk name

CDN = "https://pygame-web.github.io/archives/0.9/"
PYBUILD = "3.12"  # CPython version of the pygbag WASM runtime


def stage(build_id: str, sha: str, built_at: str) -> None:
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    shutil.copy2(WEB / "main.py", STAGE / "main.py")
    shutil.copytree(
        PACKAGE, STAGE / "jenesboat_v2", ignore=shutil.ignore_patterns("__pycache__", "*.pyc")
    )
    (STAGE / "jenesboat_v2" / "_build_info.py").write_text(
        '"""Generated by scripts/build_web.py."""\n\n'
        f"BUILD_ID = {build_id!r}\nGIT_SHA = {sha!r}\nBUILT_AT = {built_at!r}\n"
    )


def run_pygbag(build_id: str, width: int, height: int) -> Path:
    cmd = [
        sys.executable,
        "-m",
        "pygbag",
        "--build",
        "--PYBUILD",
        PYBUILD,
        "--ume_block",
        "0",
        "--can_close",
        "1",
        "--template",
        str(WEB / "noctx.tmpl"),
        "--cdn",
        CDN,
        "--title",
        f"jenesboat {build_id}",
        "--width",
        str(width),
        "--height",
        str(height),
        str(STAGE),
    ]
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=ROOT, timeout=600)
    out = STAGE / "build" / "web"
    if not (out / "index.html").is_file():
        raise SystemExit(f"pygbag did not produce {out / 'index.html'}")
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--build-id", default="dev", help="short sha, tag name or 'dev'")
    p.add_argument("--sha", default="", help="full git sha of the build")
    p.add_argument("--out", default=str(ROOT / "dist" / "web"), help="output directory")
    p.add_argument("--width", type=int, default=960)
    p.add_argument("--height", type=int, default=540)
    p.add_argument("--meta-json", default="{}", help="extra JSON object merged into build.json")
    args = p.parse_args()

    built_at = dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat()
    stage(args.build_id, args.sha, built_at)
    produced = run_pygbag(args.build_id, args.width, args.height)

    out = Path(args.out).resolve()
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(produced, out)
    meta = {
        "name": args.build_id,
        "sha": args.sha,
        "built_at": built_at,
        "pybuild": PYBUILD,
        "cdn": CDN,
    }
    meta.update(json.loads(args.meta_json))
    (out / "build.json").write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n")
    print(f"web build ready in {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
